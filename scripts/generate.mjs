/**
 * Generate the modules that let covers run without a file system:
 *
 * - `src/builtins.js`: the built-in recipes (`recipes/*.json`) as one module.
 * - `src/inter-data.js`: the bundled Inter WOFFs, base64, loaded lazily
 *   where `fonts/` can't be read (browsers, Workers).
 * - `src/version.js`: the package version.
 *
 * Run after changing a recipe, a font or the version: `npm run generate`.
 * A test checks the files are current.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root));

/** @returns {Record<string, string>} file → contents */
export function generated() {
  const names = readdirSync(new URL('recipes/', root)).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
  const recipes = Object.fromEntries(names.map((n) => [n, JSON.parse(read(`recipes/${n}.json`))]));
  const builtins = `// Generated by scripts/generate.mjs from recipes/*.json. Do not edit.\n\n/** The built-in recipe documents, by name. */\nexport const BUILTIN_JSON = ${JSON.stringify(recipes)};\n`;

  const weights = [400, 500, 600, 700];
  const fonts = weights.map((w) => `  ${w}: '${read(`fonts/inter-latin-${w}.woff`).toString('base64')}',`).join('\n');
  const inter = `// Generated by scripts/generate.mjs from fonts/*.woff. Do not edit.
// Inter is © The Inter Project Authors, SIL Open Font License 1.1 (fonts/OFL.txt).

import { fromBase64 } from './platform/index.js';

/** @type {Record<number, string>} */
const DATA = {
${fonts}
};

/** @type {Map<number, Uint8Array>} */
const cache = new Map();

/**
 * Bundled Inter (Latin) as WOFF bytes.
 *
 * @param {number} weight - 400, 500, 600 or 700.
 * @returns {Uint8Array}
 */
export function inter(weight) {
  let b = cache.get(weight);
  if (!b) cache.set(weight, (b = fromBase64(DATA[weight] ?? DATA[400])));
  return b;
}
`;
  const version = `// Generated by scripts/generate.mjs from package.json. Do not edit.\n\n/** The package version, part of every cache key. */\nexport const VERSION = '${JSON.parse(read('package.json')).version}';\n`;
  return { 'src/builtins.js': builtins, 'src/inter-data.js': inter, 'src/version.js': version };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [file, text] of Object.entries(generated())) writeFileSync(new URL(file, root), text);
  console.log('generated src/builtins.js, src/inter-data.js, src/version.js');
}
